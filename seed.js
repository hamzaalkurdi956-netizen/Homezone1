function seed(db) {
  const has = db.prepare("SELECT 1 FROM settings WHERE skey='seeded'").get();
  if (has) return false;
  db.exec('BEGIN IMMEDIATE');
  try {
    const ins = db.prepare(`INSERT INTO products(id,zone,name,spec,descr,price,old,tag,icon,active,sort)
                            VALUES(?,?,?,?,?,?,?,?,?,1,?)`);
    for (const p of PRODUCTS) ins.run(p.id, p.zone, p.name, p.spec, p.descr, p.price, p.old, p.tag, p.icon, p.sort);
    db.prepare("INSERT OR IGNORE INTO coupons(code,type,amount,min_total,active) VALUES('WELCOME10','percent',10,20,1)").run();
    const set = db.prepare('INSERT OR IGNORE INTO settings(skey,sval) VALUES(?,?)');
    set.run('freeFrom', '50'); set.run('shipFee', '3'); set.run('notice', '');
    set.run('seeded', '1');
    db.exec('COMMIT');
  } catch (e) { db.exec('ROLLBACK'); throw e; }
  return true;
}

